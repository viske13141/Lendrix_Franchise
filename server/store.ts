export function isProductAllowedForFranchisee(
  franchiseeId: string,
  category: ProductCategory
): { allowed: boolean; reason?: string } {
  const fr = store.franchises.find((f) => f.id === franchiseeId);
  if (!fr) return { allowed: false, reason: 'Franchisee account not found.' };
  if (fr.suspensionStatus === 'Suspended' || fr.exitStatus !== 'Active') {
    return { allowed: false, reason: 'Franchisee platform access is restricted due to suspension/exit status.' };
  }
  if (fr.platformActivationStatus !== 'Activated') {
    return { allowed: false, reason: 'Franchisee platform access is not yet activated.' };
  }
  const tierProducts = TIER_PRODUCTS[fr.tier];
  if (!tierProducts.includes(category)) {
    return { allowed: false, reason: `${category} is not included in ${fr.tier} tier (FR-04).` };
  }
  if (category === 'Venture Capital Services' && !fr.vcApprovedUser) {
    return { allowed: false, reason: 'Venture Capital Services is restricted to Premier-tier approved users (FR-15).' };
  }
  const lic = store.licences.find(
    (l) => l.franchiseeId === franchiseeId && l.productCategory === category
  );
  if (!lic) {
    return { allowed: false, reason: `Required regulatory licence for ${category} is Missing (FR-05).` };
  }
  if (lic.verificationStatus !== 'Verified') {
    return {
      allowed: false,
      reason: `${category} distribution is blocked because ${lic.licenceType} is ${lic.verificationStatus} (FR-05).`,
    };
  }
  return { allowed: true };
}

export function computeFr50Summary() {
  const franchiseCount = store.franchises.length;
  const franchiseActivationCount = store.franchises.filter(
    (f) => f.platformActivationStatus === 'Activated' && f.suspensionStatus === 'None'
  ).length;
  const franchiseeChurnCount = store.franchises.filter(
    (f) => f.exitStatus === 'Exited' || f.exitStatus === 'Exit Initiated' || f.suspensionStatus === 'Suspended'
  ).length;

  const eligibleOrIssuedTxns = store.transactions.filter(
    (t) => t.manufacturerStatus !== 'Rejected'
  );
  const totalSalesVolume = eligibleOrIssuedTxns.reduce((acc, t) => acc + t.amount, 0);
  const totalAum = eligibleOrIssuedTxns
    .filter((t) => t.productCategory === 'Mutual Funds' || t.productCategory === 'Venture Capital Services')
    .reduce((acc, t) => acc + t.amount, 0);
  const totalLoanDisbursals = eligibleOrIssuedTxns
    .filter((t) => t.productCategory === 'Loans' && t.manufacturerStatus === 'Disbursed')
    .reduce((acc, t) => acc + t.amount, 0);
  const totalInsurancePremiums = eligibleOrIssuedTxns
    .filter((t) => t.productCategory === 'Insurance')
    .reduce((acc, t) => acc + t.amount, 0);

  const categories: ProductCategory[] = [
    'Mutual Funds',
    'Loans',
    'Insurance',
    'Real Estate',
    'Venture Capital Services',
  ];
  const commissionByProduct = categories.map((category) => ({
    category,
    amount: store.transactions
      .filter((t) => t.productCategory === category)
      .reduce((acc, t) => acc + t.commissionAccrued, 0),
  }));

  return {
    franchiseCount,
    franchiseActivationCount,
    activeFranchiseRatioPct: franchiseCount > 0 ? Math.round((franchiseActivationCount / franchiseCount) * 100) : 0,
    totalSalesVolume,
    totalAum,
    totalLoanDisbursals,
    totalInsurancePremiums,
    franchiseeChurnCount,
    commissionByProduct,
  };
}

